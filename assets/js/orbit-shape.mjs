const TAU = Math.PI * 2;

/** Числа фігур (спільні з тлом шейдера levelfx-abra.mjs — той самий f). */
export const OS_K = Object.freeze({
  POLY_K: 0.8,       // гострота многокутника: 0 — коло, 1 — справжній (ребро трикутника 0.5 від вершини)
  STAR_K: 0.3,       // глибина променів зірки
  STAR_N: 5,
  PATH_N: 240,       // вершин лінії кільця (кути трикутника / зірки — гострі)
});

/** Стан кадру: on, ваги форми [еліпс, aspect, трикутник, квадрат, зірка], φ, τ, r0 (од. поля — радіус зовнішнього кільця), norm — вписування в кадр. */
export const OS = { on: false, we: 0, asp: 0, w3: 0, w4: 0, ws: 0, phi: 0, tw: 0, r0: 300, norm: 1 };
// [24.11, ідея «різні фігури на різних кільцях» — знято]: вершина внутрішньої фігури впирається в ребро зовнішньої — кільця сходяться до 14 од.
// (м'яч 22; навіть 35 % суміші — 41 од. < 52): рейки 130 / 225 / 320 (крок × 1.42) витримують лише однакову фігуру на всіх кільцях.

/** Середній радіус правильного n-кутника з вершиною 1 — нормування (фігура в середньому не росте й не меншає). */
export function polyMean(n) {
  const a = Math.PI / n;
  return (Math.cos(a) / a) * Math.log(Math.tan(Math.PI / 4 + a / 2));
}
const M3 = polyMean(3), M4 = polyMean(4);

/** f(θ) — радіус форми в системі фігури (θ — рад). S — { we, asp, w3, w4, ws }. */
export function shapeF(S, th) {
  let f = 1;
  if (S.we) {
    const a = 1 + S.asp, c = Math.cos(th), s = Math.sin(th);
    f += S.we * (1 / Math.sqrt((c / a) * (c / a) + (s * a) * (s * a)) - 1);
  }
  if (S.w3) { const a = TAU / 3, x = ((th % a) + a) % a - a / 2; f += S.w3 * OS_K.POLY_K * (Math.cos(Math.PI / 3) / Math.cos(x) / M3 - 1); }
  if (S.w4) { const a = TAU / 4, x = ((th % a) + a) % a - a / 2; f += S.w4 * OS_K.POLY_K * (Math.cos(Math.PI / 4) / Math.cos(x) / M4 - 1); }
  if (S.ws) { const x = (((th * OS_K.STAR_N) / TAU) % 1 + 1) % 1; f += S.ws * OS_K.STAR_K * (Math.abs(x - 0.5) * 2 - 0.5); }
  return f;
}

/** Множник радіуса точки поля (θ — рад, r — од. поля); поза формою — 1. */
export function osK(th, r) {
  if (!OS.on) return 1;
  return shapeF(OS, th - OS.phi - (OS.tw * Math.min(r, OS.r0)) / OS.r0) * OS.norm;
}

/** Точка поля на фігурі: out[0], out[1] (центр cx, cy; θ — рад). */
export function osXY(cx, cy, th, r, out) {
  const k = osK(th, r);
  out[0] = cx + Math.cos(th) * r * k; out[1] = cy + Math.sin(th) * r * k;
  return out;
}

/** Контур кільця радіуса R замість ctx.arc (поточний шлях: beginPath — у того, хто кличе). */
export function osPath(ctx, cx, cy, R) {
  if (!OS.on) { ctx.arc(cx, cy, R, 0, TAU); return; }
  const n = OS_K.PATH_N;
  for (let i = 0; i <= n; i++) {
    const th = (i / n) * TAU, k = osK(th, R);
    const x = cx + Math.cos(th) * R * k, y = cy + Math.sin(th) * R * k;
    if (i === 0) ctx.moveTo(x, y); else ctx.lineTo(x, y);
  }
  ctx.closePath();
}

/** Дуга кільця радіуса R від a0 до a1 (рад) у системі, повернутій на rot (центр — 0, 0): замість ctx.arc(0, 0, R, a0, a1). */
export function osArc(ctx, R, a0, a1, rot) {
  if (!OS.on) { ctx.arc(0, 0, R, a0, a1); return; }
  const n = Math.max(4, Math.ceil((Math.abs(a1 - a0) / TAU) * OS_K.PATH_N));
  for (let i = 0; i <= n; i++) {
    const u = a0 + ((a1 - a0) * i) / n, k = osK(u + rot, R);
    const x = Math.cos(u) * R * k, y = Math.sin(u) * R * k;
    if (i === 0) ctx.moveTo(x, y); else ctx.lineTo(x, y);
  }
}

/** Скинути форму (рамка гри — щокадру перед шаром рівня; інший рівень / меню — коло). */
export function osReset() { OS.on = false; }

// ── [495c] Ефекти на лінії (власник 26.11: «хвиля-брижа з'являється десь не на орбіті, де м'яча не було») ─────────────────────
// Разові ефекти (хвиля, розліт, напис, удар, мітка смерті, світло приземлення) ставились у точку фігури МИТІ народження й стояли там,
// а фігура далі морфиться, крутиться (φ) і перекручується (τ) — ефект «з'їжджав» з лінії. Точка поля (θ, r) на фігурі лежить на тому
// самому промені θ (k множить лише радіус), тож ефект їде за лінією зсувом уздовж променя: (k зараз − k минулого кадру) · r.
// Без форми зсув рівно 0 (k ≡ 1), і рамка гри прохід зсувів пропускає зовсім (OS.on і кадр після — щоб повернутись на коло).

/** Якір точки поля (θ — рад, r — од. поля): k цієї миті; зсув кадру — osPinStep. */
export function osPin(th, r) {
  return { th, r, k: osK(th, r), dx: 0, dy: 0, f: -1 };
}

/** Зсув якоря [p] за кадр [f] (раз на кадр, хоч би скільки ефектів його ділили): p.dx, p.dy — куди за цей кадр зсунулась точка лінії. */
export function osPinStep(p, f) {
  if (p.f === f) return p;
  p.f = f;
  const k = osK(p.th, p.r), d = (k - p.k) * p.r;
  p.k = k;
  p.dx = Math.cos(p.th) * d; p.dy = Math.sin(p.th) * d;
  return p;
}
