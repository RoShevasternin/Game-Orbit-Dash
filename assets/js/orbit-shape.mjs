//  Рушій живе в колах: кут м'яча, двері, суддя тапу не знають про форму. Тут — лише де ПОКАЗАТИ точку поля (кут θ, радіус r): на фігурі
//    P(θ, r) = центр + r · k(θ, r) · (cos θ, sin θ),   k = f(θ − φ − τ · r / R0)
//  де f — «радіус форми» (коло 1, еліпс, трикутник, квадрат, зірка — суміш вагами), φ — оберт фігури, τ — перекрут (зовнішні кільця повернуті
//  більше за внутрішні). М'яч, шипи, геми, хвіст лишаються самі собою (круглий м'яч, ті самі фігури) — міняється лише ДЕ вони стоять і якої
//  форми лінія кілець. Поза рівнем із формою OS.on = false і k ≡ 1 (жодної зміни для інших рівнів).
//  Стан — один модульний об'єкт (кадр пише шар рівня levelfx-abra, рамка гри скидає перед шаром); 0 алокацій на виклик.
