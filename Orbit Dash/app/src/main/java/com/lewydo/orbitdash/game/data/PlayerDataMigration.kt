// ----------------------------------------------------------------------------
// PlayerDataMigration — міграції збереженого стану між версіями схеми
//
//   КОЛИ потрібна міграція:
//     Більшість змін НЕ потребують міграції — достатньо дефолту поля
//     (див. правила нижче). Міграція потрібна лише для НЕсумісних змін,
//     які ignoreUnknownKeys/дефолти не покривають:
//       • змінився ТИП поля (Int → String, секунди → мілісекунди)
//       • поле розділили/об'єднали (one → two, чи навпаки)
//       • треба перерахувати значення зі старих даних
//
//   ЯК додати міграцію (приклад):
//     1) Підвищ CURRENT_VERSION (напр. 1 → 2).
//     2) Додай гілку в migrate() для старої версії.
//     3) Перетвори дані й поверни PlayerData з новою schemaVersion.
//
//   ── ПРАВИЛА ЗМІН СХЕМИ (щоб НЕ ламати старих юзерів) ──
//     ✅ Нове поле — ЗАВЖДИ з дефолтом:           val newF: Int = 0
//     ✅ Видалити поле — безпечно (ignoreUnknownKeys його проігнорує)
//     ✅ Перейменувати — через @SerialName("старе_ім'я"), НЕ міняючи ключ
//     ❌ Міняти ТИП існуючого поля — потрібна міграція (інакше fallback→default)
//     ❌ Додати поле БЕЗ дефолту — краш на старих save
// ----------------------------------------------------------------------------

object PlayerDataMigration {

    // Поточна версія схеми. Підвищуй при несумісних змінах.
    const val CURRENT_VERSION = 1

    // ------------------------------------------------------------------------
    // Точка входу — викликається ПІСЛЯ декодування, ПЕРЕД використанням
    // ------------------------------------------------------------------------

    fun migrate(data: PlayerData): PlayerData {
        var d = data
        // Послідовно проганяємо через усі версії до актуальної.
        while (d.schemaVersion < CURRENT_VERSION) {
            d = when (d.schemaVersion) {
                // 0 -> 1: приклад. Старі збереження без schemaVersion
                //          десеріалізуються з version=CURRENT (дефолт), тож
                //          сюди зазвичай не потраплять. Гілка для майбутніх змін.
                // 0 -> migrateV0toV1(d)

                // 1 -> 2: коли зробиш несумісну зміну — розкоментуй і реалізуй
                // 1 -> migrateV1toV2(d)

                else -> {
                    // Невідома/несумісна версія — лишаємо як є (поля підхопили
                    // дефолти), тільки оновлюємо номер, щоб не зациклитись.
                    log("PlayerDataMigration: немає правила для v${d.schemaVersion}, лишаю як є")
                    d.copy(schemaVersion = CURRENT_VERSION)
                }
            }
        }
        return d
    }

    // ------------------------------------------------------------------------
    // Приклади-заготовки міграцій (розкоментуй/адаптуй коли знадобиться)
    // ------------------------------------------------------------------------

    // Приклад: колись зберігали час у секундах, переходимо на мілісекунди.
    // private fun migrateV1toV2(d: PlayerData): PlayerData = d.copy(
    //     // someTimeMillis = d.someTimeSeconds * 1000L,   // перерахунок
    //     schemaVersion = 2,
    // )
}