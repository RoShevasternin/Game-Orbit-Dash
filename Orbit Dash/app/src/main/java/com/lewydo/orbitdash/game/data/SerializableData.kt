package com.lewydo.orbitdash.game.data

import kotlinx.serialization.Serializable

@Serializable
data class PlayerData(
    // Версія схеми — підвищуй при НЕсумісних змінах (зміна типу поля тощо).
    // Сумісні зміни (нове поле з дефолтом) версію змінювати НЕ потребують.
    val schemaVersion : Int = PlayerDataMigration.CURRENT_VERSION,

    /**
     * Стабільний анонімний ID гравця. Народжується один раз при першому
     * запуску, живе в сейві: переживає перевстановлення через бекап,
     * але НЕ прив'язаний до акаунта — це не PII. Споживачі: userId в
     * аналітиці, ключ лідерборда.
     */
    val pid    : String = "",

    val skinId : Int  = 0,

    // ------------------------------------------------------------------------
    // Економіка й прогрес
    // ------------------------------------------------------------------------

    /** Валюта. Int, а не Long: 2.1 млрд гемів недосяжні при ~20 за ран. */
    val gems   : Int = 0,

    /** Рекорд рану. Джерело для NEW BEST, підпису в меню і best_bucket. */
    val best   : Int = 0,

    /** Скільки ранів зіграно всього. Потрібен туторіалу і місіям; це ж і лідерборд програшів. */
    val runs   : Int = 0,

    /** Скільки комбо за всю гру. Лідерборд COMBO. Поки комбо = прохід впритул повз шип. */
    val comboTotal: Int = 0,

    // ------------------------------------------------------------------------
    // Покупки
    // ------------------------------------------------------------------------

    /** Третя орбіта з 30-ї секунди. Читає RunEngine.Config. */
    val orbit3 : Boolean = false,

    /** Прибирає банер/MREC/interstitial. Rewarded лишається — це не покупка. */
    val noAds  : Boolean = false,

    // ------------------------------------------------------------------------
    // Звук — повзунки гравця, 0..1
    // ------------------------------------------------------------------------
    //
    //  Тільки те, що крутить ГРАВЕЦЬ. Вага окремого звуку (coff) — авторська,
    //  живе в коді, у сейв не потрапляє: інакше перебалансування міксу не
    //  доїхало б до тих, хто вже грає. Формула — AudioMixer.
    //
    //  Дефолт 1: гра має звучати на повну одразу після встановлення, а тихіше
    //  зробить системний регулятор. Нові поля з дефолтом — міграція не потрібна.
    //
    /** Майстер: один повзунок на музику й ефекти разом. */
    val volMaster : Float = 1f,
    /** Шина музики. */
    val volMusic  : Float = 1f,
    /** Шина ефектів. */
    val volSfx    : Float = 1f,
)