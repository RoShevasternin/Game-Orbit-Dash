package com.lewydo.orbitdash.game.manager.util

import com.lewydo.orbitdash.game.utils.gdxGame
import kotlinx.coroutines.flow.Flow
import kotlinx.coroutines.flow.combine
import kotlinx.coroutines.flow.distinctUntilChanged

// ----------------------------------------------------------------------------
//  МІКШЕРНИЙ ПУЛЬТ — ОДНЕ МІСЦЕ, ДЕ ГУЧНІСТЬ ПЕРЕТВОРЮЄТЬСЯ НА ЧИСЛО.
//
//  Тракт має рівно три рівні, і в кожного один господар:
//
//    coff  ─ АВТОР. Вага ассета в міксі, 0..1. Ставиться раз, при створенні:
//            у синтезованих звуків рахується з піка рецепта, у треку стоїть
//            у MusicManager.EnumMusic. Гравець її не бачить і не крутить.
//    шина  ─ ГРАВЕЦЬ. Повзунки MUSIC і SFX у налаштуваннях, 0..1. Живуть у
//            сейві (PlayerData.volMusic / volSfx), тож переживають перезапуск.
//    майстер ─ ГРАВЕЦЬ. Один повзунок на все, 0..1 (PlayerData.volMaster).
//
//  І ВСЕ. Системної гучності телефона в формулі НЕМАЄ — її накладає Android
//  поверх нашого числа. Раніше ми множили на неї самі, і вона прикладалась
//  двічі: на 50 % гучності гра звучала на 25 %, на 25 % — на 6 %. Саме через
//  це синтезовані звуки й здавались «відсутніми» (патч 71).
//
//  ── Чому повзунок не лінійний ───────────────────────────────────────────
//  Вухо чує гучність приблизно логарифмічно: половина амплітуди — це не
//  «удвічі тихіше», а ледь помітно тихіше. Лінійний повзунок тому відчувається
//  зламаним: перші 70 % ходу майже нічого не міняють, а решта різко глушить.
//  curve() = x² (−12 дБ на середині) робить хід рівномірним на слух. Кожна
//  шина проходить криву окремо, тому два повзунки на 50 % дають −24 дБ — так
//  само, як два фейдери на −12 дБ у справжньому пульті.
//
//  ── Запас під суму ──────────────────────────────────────────────────────
//  SoundPool мікс просто ДОДАЄ доріжки. Тап + гем + комбо можуть зійтись у
//  тих самих 50 мс і дати суму понад одиницю — це кліп, чутний як тріск.
//  SFX_HEADROOM лишає 2 дБ запасу; музика його не потребує (доріжка одна).
// ----------------------------------------------------------------------------
object AudioMixer {

    /** Запас під суму одночасних ефектів. ~2 дБ: чутно не стає тихіше, кліпу немає. */
    const val SFX_HEADROOM = 0.8f

    // ── Чиста математика: без Gdx і без стану, тому тестується на JVM ───────

    /** Повзунок 0..1 → підсилення 0..1. x²: рівномірно на слух, −12 дБ на середині. */
    fun curve(slider: Float): Float = slider.coerceIn(0f, 1f).let { it * it }

    /**
     * Фінальне число для `Sound.play()` / `Music.volume`.
     *
     * @param coff     вага ассета (автор)
     * @param bus      повзунок шини (гравець)
     * @param master   майстер-повзунок (гравець)
     * @param headroom запас під суму доріжок; 1 = без запасу
     */
    fun gain(coff: Float, bus: Float, master: Float, headroom: Float = 1f): Float =
        (coff.coerceIn(0f, 1f) * curve(bus) * curve(master) * headroom).coerceIn(0f, 1f)

    /** Формула ефекту з ЯВНИМИ повзунками: те саме, що sfx(), але без сейву — тести й дебаг. */
    fun sfxAt(coff: Float, bus: Float, master: Float, playCoff: Float = 1f): Float =
        gain(coff * playCoff.coerceIn(0f, 1f), bus, master, SFX_HEADROOM)

    // ── Живі значення з сейву ───────────────────────────────────────────────

    private val player get() = gdxGame.modelPlayer

    /**
     * Шина музики БЕЗ coff треку: master × music. Трек домножує свій coff сам —
     * так один потік обслуговує будь-який трек, і зміна повзунка чутна одразу,
     * поки палець ще на ньому.
     */
    val musicBusFlow: Flow<Float>
        get() = combine(player.volMasterFlow, player.volMusicFlow) { m, mus ->
            gain(1f, mus, m)
        }.distinctUntilChanged()

    /** Те саме значення «просто зараз» — для щойно запущеного треку. */
    fun musicBus(): Float = gain(1f, player.volMusic, player.volMaster)

    /** Гучність ефекту: вага ассета × шина SFX × майстер × запас. */
    fun sfx(coff: Float, playCoff: Float = 1f): Float =
        sfxAt(coff, player.volSfx, player.volMaster, playCoff)

    /** Ефекти вимкнені повзунком — черга навіть не потрібна. */
    val isSfxSilent: Boolean get() = player.volSfx <= 0f || player.volMaster <= 0f
}
